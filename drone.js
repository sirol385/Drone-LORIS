function isShort(url) { return url && url.includes('/shorts/'); }
function ytId(url) {
  if (!url || url.includes('REMPLACEZ')) return null;
  const m = url.match(/(?:shorts\/|v=|youtu\.be\/|embed\/)([a-zA-Z0-9_-]{11})/);
  return m ? m[1] : null;
}
function ytThumb(id) { return `https://i.ytimg.com/vi/${id}/hqdefault.jpg`; }
function ytWatch(id, short) {
  return short ? `https://www.youtube.com/shorts/${id}` : `https://www.youtube.com/watch?v=${id}`;
}
function scrollToSection(key) {
  const el = document.querySelector(`[data-section="${key}"]`);
  if (!el) return;
  const doScroll = () => {
    const navH = parseInt(getComputedStyle(document.documentElement).getPropertyValue('--nav-h')) || 64;
    const top = el.getBoundingClientRect().top + window.scrollY - navH;
    window.scrollTo({ top: top, behavior: 'smooth' });
  };
  if (document.getElementById('lieu-page').classList.contains('open')) {
    closeLieuPage();
    setTimeout(doScroll, 80);
  } else {
    doScroll();
  }
}
function initHeroMosaic() {
  const mosaic = document.getElementById('hero-mosaic');
  if (!mosaic) return;
  const ids = [];
  Object.values(DATA).forEach(lieu => {
    lieu.videos.forEach(v => {
      const id = ytId(v.url);
      if (id) ids.push(id);
    });
  });
  const needed = 24;
  if (ids.length === 0) { mosaic.style.display = 'none'; return; }
  const tiles = [];
  while (tiles.length < needed) tiles.push(...ids);
  tiles.splice(needed);
  tiles.forEach(id => {
    const img = document.createElement('img');
    img.src = ytThumb(id);
    img.alt = '';
    img.loading = 'lazy';
    mosaic.appendChild(img);
  });
}
