function animateCounter(el, target) {
  let n = 0;
  const steps = 50;
  const interval = 1400 / steps;
  const increment = target / steps;
  const iv = setInterval(() => {
    n = Math.min(n + increment, target);
    el.textContent = Math.round(n);
    if (Math.round(n) >= target) { el.textContent = target; clearInterval(iv); }
  }, interval);
}
function initCounters() {
  document.querySelectorAll('.hstat-n[data-key]').forEach(el => {
    const key = el.dataset.key;
    if (key === 'videos') el.dataset.target = NB_VIDEOS;
    if (key === 'lieux')  el.dataset.target = NB_LIEUX;
    if (key === 'km')     el.dataset.target = KM_PARCOURUS;
  });
  const els = document.querySelectorAll('.hstat-n[data-target]');
  const obs = new IntersectionObserver(entries => {
    entries.forEach(e => {
      if (!e.isIntersecting) return;
      const el = e.target;
      const target = +el.dataset.target;
      if (!target) { el.textContent = '—'; return; }
      animateCounter(el, target);
      obs.unobserve(el);
    });
  }, { threshold: .5 });
  els.forEach(el => { el.textContent = '0'; obs.observe(el); });
}
function initScrollAnim() {
  const els = document.querySelectorAll('.lieu-card, .service-item, .apropos-text, .drone-badge');
  els.forEach(el => {
    el.style.opacity = '0';
    el.style.transform = 'translateY(18px)';
    el.style.transition = 'opacity .7s ease, transform .7s cubic-bezier(.16,1,.3,1)';
  });
  const obs = new IntersectionObserver(entries => {
    entries.forEach((e, i) => {
      if (!e.isIntersecting) return;
      setTimeout(() => { e.target.style.opacity = '1'; e.target.style.transform = 'none'; }, i * 55);
      obs.unobserve(e.target);
    });
  }, { threshold: .08 });
  els.forEach(el => obs.observe(el));
}
